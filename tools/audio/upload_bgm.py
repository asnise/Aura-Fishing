"""Upload the BGM files in assets/bgm/*.mp3 to Roblox as Audio (Open Cloud), then write the ids to
assets/bgm/ids.json and src/shared/Config/SoundAssets.luau (Config/Sounds picks them up by file name).

Run it yourself in a terminal (it asks for your API key; the key is never saved or printed):
    python -I tools/audio/upload_bgm.py --user <yourUserId>      (or --group <groupId>)
Options: --only The_Dock_at_Daybreak,Morning_By_The_Dock   --dry-run
Resumable: files that already have an id in ids.json are skipped.

API key: create.roblox.com -> Open Cloud -> API Keys -> Create: add API system "Assets" with Read + Write,
accepted IP 0.0.0.0/0 (or yours). Audio is moderated by Roblox (usually a few minutes); a rejected upload shows
up as an error here. Audio uploads are limited per month for accounts without ID verification.
"""
import getpass
import glob
import json
import os
import sys
import time
import urllib.error
import urllib.request
import uuid

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BGM = os.path.join(ROOT, "assets", "bgm")
IDS = os.path.join(BGM, "ids.json")
LUAU = os.path.join(ROOT, "src", "shared", "Config", "SoundAssets.luau")
API = "https://apis.roblox.com/assets/v1/"


def arg(name):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else None


def request(method, url, key, body=None, headers=None):
    req = urllib.request.Request(url, data=body, method=method, headers={"x-api-key": key, **(headers or {})})
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            return json.loads(r.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        raise RuntimeError(f"HTTP {e.code}: {e.read().decode('utf-8', 'replace')[:300]}") from None


def upload(path, name, creator, key):
    boundary = uuid.uuid4().hex
    meta = {
        "assetType": "Audio",
        "displayName": name[:50],
        "description": "Aura Fishing BGM",
        "creationContext": {"creator": creator},
    }
    data = open(path, "rb").read()
    body = (
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"request\"\r\n\r\n{json.dumps(meta)}\r\n"
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"fileContent\"; filename=\"{os.path.basename(path)}\"\r\n"
        "Content-Type: audio/mpeg\r\n\r\n"
    ).encode() + data + f"\r\n--{boundary}--\r\n".encode()
    op = request("POST", API + "assets", key, body, {"Content-Type": f"multipart/form-data; boundary={boundary}"})
    for _ in range(90):
        if op.get("done"):
            res = op.get("response", {})
            if "assetId" in res:
                return res["assetId"]
            raise RuntimeError(f"upload finished without assetId: {json.dumps(op)[:300]}")
        time.sleep(3)
        op = request("GET", API + op["path"], key)
    raise RuntimeError("timed out waiting for the upload operation")


def write_luau(ids):
    lines = [
        "--!strict",
        "-- GENERATED by tools/audio/upload_bgm.py - do not edit by hand.",
        "-- Roblox audio asset ids by file name (assets/bgm/<name>.mp3). Used by Config/Sounds.",
        "local SoundAssets: { [string]: string } = {",
    ]
    for name in sorted(ids):
        lines.append(f'\t["{name}"] = "rbxassetid://{ids[name]}",')
    lines += ["}", "", "return SoundAssets", ""]
    open(LUAU, "w", encoding="utf-8", newline="\n").write("\n".join(lines))


def main():
    user, group = arg("--user"), arg("--group")
    if user and group:
        print(__doc__)
        sys.exit(2)
    ids = json.load(open(IDS, encoding="utf-8")) if os.path.exists(IDS) else {}
    only = set(arg("--only").split(",")) if arg("--only") else None
    files = sorted(glob.glob(os.path.join(BGM, "*.mp3")))
    todo = []
    for f in files:
        name = os.path.splitext(os.path.basename(f))[0]
        if name not in ids and (not only or name in only):
            todo.append(f)
    print(f"{len(todo)} file(s) to upload")
    if "--dry-run" in sys.argv or not todo:
        for f in todo:
            print("  ", os.path.basename(f))
        return
    if not (user or group):
        print("Your Roblox User ID = the number in your profile URL: roblox.com/users/<UserId>/profile")
        user = input("Roblox User ID: ").strip()
        if not user.isdigit():
            print("User ID must be a number")
            sys.exit(2)
    creator = {"userId": str(user)} if user else {"groupId": str(group)}
    key = os.environ.get("ROBLOX_API_KEY") or getpass.getpass("Roblox Open Cloud API key (hidden): ").strip()
    for f in todo:
        name = os.path.splitext(os.path.basename(f))[0]
        try:
            ids[name] = upload(f, name, creator, key)
        except Exception as e:  # keep going; re-run later resumes
            print(f"  FAIL {name}: {e}")
            if "HTTP 401" in str(e) or "HTTP 403" in str(e):
                print("  -> check the API key permissions (Assets: Read + Write) and the creator id")
                break
            continue
        json.dump(ids, open(IDS, "w", encoding="utf-8"), indent=1)  # save after each one
        write_luau(ids)
        print(f"  ok {name} -> {ids[name]}")
        time.sleep(1.5)
    print("done. Then run: node tools/check.mjs")


if __name__ == "__main__":
    main()
