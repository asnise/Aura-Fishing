import json
import os

def generate_luau():
    with open('assets/catalog.json', 'r', encoding='utf-8') as f:
        cat = json.load(f)

    tree = {
        'Icons': {'Global': {}, 'Menu': {}, 'Status': {}},
        'Items': {'Rods': {}, 'Lines': {}, 'Baits': {}, 'Bags': {}, 'Materials': {}},
        'Auras': {'Orbs': {}, 'ArtCards': {}},
        'Fish': {'Species': {}, 'Mutations': {}, 'Decorations': {}},
        'UI': {'Backgrounds': {}, 'Shop': {}, 'Tabs': {}, 'Mastery': {}, 'Shapes': {}},
        'NPC': {'Portraits': {}}
    }

    key_map = {}

    for k, v in cat.get('global', {}).items():
        aid = v.get('rbxassetid') or ''
        key_map[k] = {'key': k, 'id': aid}
        if k.startswith('icon_'):
            tree['Icons']['Global'][k] = aid
        else:
            tree['UI']['Shapes'][k] = aid

    for k, v in cat.get('art', {}).items():
        aid = v.get('rbxassetid') or ''
        key_map[k] = {'key': k, 'id': aid}
        parts = k.split('/')
        folder = parts[0]
        name = parts[1] if len(parts) > 1 else parts[0]

        if folder == 'auras':
            tree['Auras']['Orbs'][name] = aid
        elif folder == 'auras_Art':
            tree['Auras']['ArtCards'][name] = aid
        elif folder == 'npc':
            tree['NPC']['Portraits'][name] = aid
        elif folder == 'materials':
            tree['Items']['Materials'][name] = aid
        elif folder == 'equipment':
            if 'Rod' in name:
                tree['Items']['Rods'][name] = aid
            elif 'Line' in name:
                tree['Items']['Lines'][name] = aid
            elif any(b in name for b in ['Bait', 'Worm', 'Shrimp', 'GlowGrub']):
                tree['Items']['Baits'][name] = aid
            else:
                tree['Items']['Bags'][name] = aid
        elif folder == 'fish':
            if name.startswith('mut_'):
                tree['Fish']['Mutations'][name] = aid
            elif name.startswith('deco_'):
                tree['Fish']['Decorations'][name] = aid
            else:
                tree['Fish']['Species'][name] = aid
        elif folder == 'ui':
            sub = parts[1] if len(parts) > 2 else ''
            actual_name = parts[2] if len(parts) > 2 else parts[1]
            if sub == 'icons':
                tree['Icons']['Menu'][actual_name] = aid
            elif sub == 'status':
                tree['Icons']['Status'][actual_name] = aid
            elif sub == 'shop':
                tree['UI']['Shop'][actual_name] = aid
            elif sub == 'tabs':
                tree['UI']['Tabs'][actual_name] = aid
            elif sub == 'mastery':
                tree['UI']['Mastery'][actual_name] = aid
            elif 'gacha_bg' in name:
                tree['UI']['Backgrounds'][actual_name] = aid

    lines = [
        '--!nonstrict',
        '-- Generated by tools/art/build_assets_tree.py',
        '-- Builds ReplicatedStorage.Assets hierarchy in Roblox Studio',
        '',
        'local rs = game:GetService("ReplicatedStorage")',
        '',
        'local existing = rs:FindFirstChild("Assets")',
        'if existing then',
        '    existing:Destroy()',
        'end',
        '',
        'local root = Instance.new("Folder")',
        'root.Name = "Assets"',
        'root.Parent = rs',
        ''
    ]

    for cat_name, subs in tree.items():
        lines.append(f'-- {cat_name}')
        lines.append(f'local folder_{cat_name} = Instance.new("Folder")')
        lines.append(f'folder_{cat_name}.Name = "{cat_name}"')
        lines.append(f'folder_{cat_name}.Parent = root')
        lines.append('')
        for sub_name, items in subs.items():
            lines.append(f'local folder_{cat_name}_{sub_name} = Instance.new("Folder")')
            lines.append(f'folder_{cat_name}_{sub_name}.Name = "{sub_name}"')
            lines.append(f'folder_{cat_name}_{sub_name}.Parent = folder_{cat_name}')
            for item_name, aid in sorted(items.items()):
                clean_aid = aid if aid else ""
                lines.append('do')
                lines.append('    local d = Instance.new("Decal")')
                lines.append(f'    d.Name = "{item_name}"')
                lines.append(f'    d.Texture = "{clean_aid}"')
                lines.append(f'    d:SetAttribute("AssetId", "{clean_aid}")')
                lines.append(f'    d:SetAttribute("Category", "{cat_name}")')
                lines.append(f'    d:SetAttribute("SubCategory", "{sub_name}")')
                lines.append(f'    d.Parent = folder_{cat_name}_{sub_name}')
                lines.append('end')
            lines.append('')

    lines.append('return "Successfully generated ReplicatedStorage.Assets with all categories!"')
    
    output_path = 'tools/art/setup_assets_tree.luau'
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print(f'Wrote {output_path}')

if __name__ == '__main__':
    generate_luau()
