// Builds the Figma plugin runtime files from sources:
//   src/main.js (+ imports)            -> code.js   (plugin main thread)
//   ui/index.html + styles.css + src/  -> ui.html   (plugin iframe UI)
// Figma loads code.js / ui.html as single files (manifest.json), so both are
// GENERATED. Edit src/ and ui/, then run:  bun run build:plugin   (or --watch)
import * as esbuild from "esbuild";
import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const here = dirname(fileURLToPath(import.meta.url));
const watch = process.argv.includes("--watch");
const BANNER = "// GENERATED by build.mjs from src/ - do not edit this file, edit src/ and rebuild.";

const common = {
  bundle: true,
  format: "iife",
  // Figma's plugin sandbox runs modern JS; es2020 keeps ?. and spread as-is.
  target: "es2020",
  minify: false,
  legalComments: "none",
  logLevel: "warning",
};

async function buildCode() {
  await esbuild.build({
    ...common,
    entryPoints: [join(here, "src/main.js")],
    outfile: join(here, "code.js"),
    banner: { js: BANNER },
  });
}

async function buildUi() {
  const js = await esbuild.build({
    ...common,
    entryPoints: [join(here, "ui/src/main.js")],
    write: false,
  });
  const css = readFileSync(join(here, "ui/styles.css"), "utf8");
  const tpl = readFileSync(join(here, "ui/index.html"), "utf8");
  const script = js.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
  const html = tpl
    .replace("/*@inline styles.css*/", () => "\n" + css)
    .replace("/*@inline ui.js*/", () => "\n" + script)
    .replace("<!DOCTYPE html>", "<!DOCTYPE html>\n<!-- GENERATED by build.mjs from ui/ - do not edit this file. -->");
  writeFileSync(join(here, "ui.html"), html);
}

async function buildAll() {
  const t = Date.now();
  await Promise.all([buildCode(), buildUi()]);
  console.log(`[plugin] built code.js + ui.html in ${Date.now() - t}ms`);
}

await buildAll();

if (watch) {
  const { watch: fsWatch } = await import("fs");
  let timer = null;
  for (const dir of ["src", "ui"]) {
    fsWatch(join(here, dir), { recursive: true }, () => {
      clearTimeout(timer);
      timer = setTimeout(() => buildAll().catch((e) => console.error(e.message)), 100);
    });
  }
  console.log("[plugin] watching src/ and ui/ ...");
}
